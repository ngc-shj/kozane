/*
 * kozane_client.h: the C ABI of the Kozane client (M9 plan C9).
 *
 * The caller owns all I/O: it sends KZ_ACTION_SEND payloads to the
 * configured rp_endpoint, passes every datagram from it to
 * kz_client_on_datagram, and calls kz_client_on_timer at
 * kz_client_next_deadline. After each kz_client_new and on_* call it takes
 * every queued action with kz_client_take_action until KZ_NONE.
 *
 * The caller wipes the key buffers it passed to kz_client_new, and every
 * PSK buffer once installed. For KZ_ACTION_SCRUB the caller removes the
 * gateway's WireGuard peer and re-adds it with a random PSK itself.
 */

