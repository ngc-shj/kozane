//! Hashing for resolved `program_image` files, via the `sha2` crate rather
//! than a hand-rolled implementation (these hashes feed measured-boot
//! records later, and this project does not write its own crypto).

use sha2::{Digest, Sha256};

/// Returns the lowercase hex digest of `data`.
pub fn hex_digest(data: &[u8]) -> String {
    let digest = Sha256::digest(data);
    digest.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_string() {
        assert_eq!(
            hex_digest(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
    }

    #[test]
    fn abc() {
        assert_eq!(
            hex_digest(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }
}
